const { queryDatabaseAll, createPage, updatePage, getPlainText } = require('./notion');
const { id: configId } = require('./ids');
const qi = require('./qi-rm');
const cr = require('./cap-review');
const rt = require('./risk-tool');
const pol = require('./policies');

// Everything the Monthly QI & RM Status and Compliance Report (ASRS-620-06)
// needs for one month, gathered from the dashboard:
//   Sections 2-3  QI & RM objectives and results (lib/qi-rm.js)
//   Section 4     CAP Review: open citations, and those closed since the
//                 start of the previous quarter (lib/cap-review.js)
//   Section 5, 7  the Risk Tracking Tool in Google Drive (lib/risk-tool.js)
//   Section 6     Liaison app questionnaires completed in the month, and
//                 the issues and opportunities log
//   Section 1, 8  pre-checked where the dashboard has the record
// plus the report details entered on the tab (QI Monthly Reports).

const REPORTS_DB = configId('QI_REPORTS_DB_ID');
const RESPONSES_DB = configId('QUESTIONNAIRE_RESPONSES_DB_ID');
const MONTHS = rt.MONTHS;

function monthLabel(m) { return MONTHS[Number(m.slice(5, 7)) - 1] + ' ' + m.slice(0, 4); }
function inMonth(iso, m) { return !!iso && String(iso).slice(0, 7) === m; }
function dueDate(m) { const n = qi.shiftMonth(m, 1); return n + '-15'; }
function quarterStart(m) { const mo = Number(m.slice(5, 7)); const q0 = Math.floor((mo - 1) / 3) * 3 + 1; return m.slice(0, 4) + '-' + String(q0).padStart(2, '0') + '-01'; }

function richText(s) { const t = String(s == null ? '' : s); return { rich_text: t ? [{ text: { content: t.slice(0, 2000) } }] : [] }; }
function dateProp(iso) { return { date: iso ? { start: iso } : null }; }

function infoFromPage(p) {
  const r = p.properties;
  return {
    id: p.id,
    month: getPlainText(r['Month']),
    preparedBy: getPlainText(r['Prepared By']),
    datePrepared: getPlainText(r['Date Prepared']),
    meetingDate: getPlainText(r['Meeting Date']),
    attendees: getPlainText(r['Attendees']),
    riskToolLink: getPlainText(r['Risk Tool Link']),
    riskToolFile: getPlainText(r['Risk Tool File']),
    generatedDate: getPlainText(r['Generated Date']),
    generatedBy: getPlainText(r['Generated By'])
  };
}

// The month's saved details; a new month starts from the last report's
// Risk Tracking Tool link (or the default).
async function reportInfo(month) {
  const rows = (await queryDatabaseAll(REPORTS_DB, null)).map(infoFromPage);
  const mine = rows.find(function (r) { return r.month === month; });
  const lastLink = rows.filter(function (r) { return r.riskToolLink && r.month <= month; }).sort(function (a, b) { return a.month < b.month ? 1 : -1; })[0];
  return Object.assign({ month: month, preparedBy: '', datePrepared: '', meetingDate: '', attendees: '', riskToolLink: '' }, mine || {}, {
    riskToolLink: (mine && mine.riskToolLink) || (lastLink && lastLink.riskToolLink) || configId('RISK_TOOL_DEFAULT_LINK')
  });
}

async function saveReportInfo(input, by) {
  const month = input.month;
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(month || '')) throw qi.httpError(400, 'Choose a month.');
  ['datePrepared', 'meetingDate'].forEach(function (k) { if (input[k] && !/^\d{4}-\d{2}-\d{2}$/.test(input[k])) throw qi.httpError(400, 'Choose valid dates.'); });
  const link = String(input.riskToolLink || '').trim();
  if (link && !rt.fileIdFromLink(link)) throw qi.httpError(400, 'The Risk Tracking Tool link should be a Google Drive link to the file.');
  const props = {
    'Month': { title: [{ text: { content: month } }] },
    'Prepared By': richText(String(input.preparedBy || '').slice(0, 200)),
    'Date Prepared': dateProp(input.datePrepared || ''),
    'Meeting Date': dateProp(input.meetingDate || ''),
    'Attendees': richText(String(input.attendees || '').slice(0, 1000)),
    'Risk Tool Link': { url: link || null }
  };
  const existing = (await queryDatabaseAll(REPORTS_DB, { property: 'Month', title: { equals: month } }))[0];
  const page = existing ? await updatePage(existing.id, props) : await createPage(REPORTS_DB, props);
  return infoFromPage(page);
}

async function markGenerated(info, fileName, by) {
  const props = { 'Generated Date': dateProp(qi.todayIso()), 'Generated By': richText(by), 'Risk Tool File': richText(fileName || '') };
  if (info.id) await updatePage(info.id, props);
  else await createPage(REPORTS_DB, Object.assign({ 'Month': { title: [{ text: { content: info.month } }] }, 'Risk Tool Link': { url: info.riskToolLink || null } }, props));
}

async function questionnaires(month) {
  if (!RESPONSES_DB) return [];
  const pages = await queryDatabaseAll(RESPONSES_DB, { property: 'Active', checkbox: { equals: true } });
  return pages.map(function (p) {
    const r = p.properties;
    return {
      submittedAt: getPlainText(r['Submitted At']), audience: getPlainText(r['Audience']), location: getPlainText(r['Location']),
      resident: getPlainText(r['Resident Initials']), spokeWith: getPlainText(r['Spoke With']), liaison: getPlainText(r['Liaison']),
      pdfLink: getPlainText(r['PDF Link'])
    };
  }).filter(function (q) { return inMonth(q.submittedAt, month); })
    .sort(function (a, b) { return a.submittedAt < b.submittedAt ? -1 : 1; });
}

async function capSection(month) {
  const caps = await cr.capsForLocations(cr.LOCATIONS);
  const details = [];
  for (const c of caps) details.push(await cr.capDetail(c.id));
  const since = qi.shiftMonth(quarterStart(month).slice(0, 7), -3) + '-01';
  const end = qi.monthEnd(month);
  return {
    since: since,
    caps: details.map(function (d) {
      const items = d.items;
      return {
        cap: d.cap,
        total: items.length,
        open: items.filter(function (i) { return i.status !== 'Closed'; }).length,
        closedThisMonth: items.filter(function (i) { return i.status === 'Closed' && inMonth(i.closedDate, month); }).length,
        openItems: items.filter(function (i) { return i.status !== 'Closed'; }),
        closedSince: items.filter(function (i) { return i.status === 'Closed' && i.closedDate >= since && i.closedDate <= end; }),
        updatedAll: items.filter(function (i) { return i.status !== 'Closed'; }).every(function (i) { return i.updates.some(function (u) { return inMonth(u.date, month); }); }),
        importedThisMonth: inMonth(d.cap.importedDate, month),
        closedOutThisMonth: d.cap.status === 'Closed' && items.some(function (i) { return inMonth(i.closedDate, month); })
      };
    })
  };
}

function itemStats(items, month) {
  const end = qi.monthEnd(month);
  const ids = function (list) { return list.map(function (i) { return 'QI-' + i.number; }); };
  const active = items.filter(function (i) { return i.status === 'Open' || i.status === 'On hold'; });
  const touched = active.filter(function (i) { return i.updates.some(function (u) { return inMonth(u.date, month); }); });
  const overdue = active.filter(function (i) { return i.due && i.due <= end && i.due < qi.todayIso(); });
  const completed = items.filter(function (i) { return i.status === 'Completed' && inMonth(i.completed, month); });
  const added = items.filter(function (i) { return inMonth(i.dateAdded, month); });
  const promotedDropped = items.filter(function (i) { return (i.status === 'Promoted to Plan' || i.status === 'Dropped') && i.updates.some(function (u) { return (u.kind === 'Promoted' || u.kind === 'Dropped') && inMonth(u.date, month); }); });
  return {
    active: active.length, updated: touched.length, notUpdated: ids(active.filter(function (i) { return touched.indexOf(i) === -1; })),
    overdue: ids(overdue), completed: ids(completed),
    added: added.map(function (i) { return 'QI-' + i.number + (i.source ? ' (' + i.source + ')' : ''); }),
    promotedDropped: promotedDropped.map(function (i) { return 'QI-' + i.number + ' ' + (i.status === 'Dropped' ? 'dropped' : 'promoted'); })
  };
}

// The whole report's data. Each source that fails is reported in
// `problems` and its section is left to fill in by hand.
async function gather(month) {
  const info = await reportInfo(month);
  const problems = [];
  const [obj, items, caps, qs, pp] = await Promise.all([
    qi.objectivesView(month),
    qi.itemsView(),
    capSection(month).catch(function (e) { problems.push('CAP Review: ' + e.message); return null; }),
    questionnaires(month).catch(function (e) { problems.push('Liaison questionnaires: ' + e.message); return null; }),
    pol.ppSummary(month).catch(function (e) { problems.push('Policy register: ' + e.message); return null; })
  ]);
  let risk = null;
  try {
    risk = rt.forMonth(await rt.loadRiskTool(info.riskToolLink), month);
  } catch (e) {
    problems.push('Risk Tracking Tool: ' + e.message);
  }
  const mo = Number(month.slice(5, 7));
  const quarterEnd = mo === 1 || mo === 4 || mo === 7 || mo === 10;
  const objectives = obj.objectives;
  const entered = objectives.filter(function (o) { return o.result && (o.result.status || o.result.valueText || o.result.total); }).length;
  const followUps = objectives.filter(function (o) { return o.result && (o.result.status === 'At risk' || o.result.status === 'Not met'); });
  const missingFollow = followUps.filter(function (o) { return !o.result.cause || !o.result.revisedAction; });
  const versionAdopted = obj.versions.find(function (v) { return inMonth(v.effective, month); }) || null;
  const draftsThisMonth = obj.drafts.filter(function (d) { return inMonth(d.updatedDate, month); });
  const stats = itemStats(items.items, month);
  const prechecks = {
    sources: {
      riskTool: !!(risk && risk.reviews.length && risk.compliance.complete),
      rcaLog: !!(risk && risk.careConcerns),
      capTrackers: !!(caps && caps.caps.length && caps.caps.every(function (c) { return !c.open || c.updatedAll; })),
      notionChecklist: false,
      objectiveSources: entered === objectives.length && objectives.length > 0,
      residentInput: !!(qs && qs.length),
      qiTracker: stats.active > 0 && stats.notUpdated.length === 0
    },
    version: {
      goal: false,
      objective: draftsThisMonth.length > 0 || !!(versionAdopted && versionAdopted.changes),
      service: false,
      riskManager: false,
      cap: !!(caps && caps.caps.some(function (c) { return c.importedThisMonth || c.closedOutThisMonth; })),
      annual: mo === 1
    }
  };
  return {
    month: month, monthLabel: monthLabel(month), due: dueDate(month), quarterEnd: quarterEnd, january: mo === 1,
    info: info, plan: obj.plan, versions: obj.versions, versionAdopted: versionAdopted, drafts: obj.drafts, draftsThisMonth: draftsThisMonth,
    goals: obj.goals, objectives: objectives, entered: entered, followUps: followUps, missingFollow: missingFollow,
    caps: caps, questionnaires: qs, items: stats, risk: risk, policies: pp && pp.loaded ? pp : null, prechecks: prechecks, problems: problems
  };
}

// The readiness summary shown before generating.
function summary(d) {
  const r = d.risk;
  return {
    month: d.month, monthLabel: d.monthLabel, due: d.due, quarterEnd: d.quarterEnd, info: d.info, problems: d.problems,
    objectives: { total: d.objectives.length, entered: d.entered, followUps: d.followUps.length, missingFollow: d.missingFollow.map(function (o) { return o.code + (o.service ? ' ' + o.service : ''); }) },
    caps: d.caps ? d.caps.caps.map(function (c) { return { title: c.cap.title, total: c.total, open: c.open, closedThisMonth: c.closedThisMonth, closedSince: c.closedSince.length }; }) : null,
    capsSince: d.caps ? d.caps.since : '',
    questionnaires: d.questionnaires ? d.questionnaires.length : null,
    policies: d.policies ? { scheduled: d.policies.scheduled, triggered: d.policies.triggered.length, revised: d.policies.revised.length, overdue: d.policies.overdue.count, reviewDocs: d.policies.reviewDocs.length } : null,
    items: d.items,
    risk: r ? {
      file: r.file.name,
      reviews: r.reviews.length,
      complianceRows: r.compliance.rows, complianceUnmarked: r.compliance.unmarked, complianceComplete: r.compliance.complete,
      findings: r.compliance.findings.length,
      incidents: [r.incidents.levelI, r.incidents.levelII, r.incidents.levelIII],
      quarter: r.quarter ? { n: r.quarter.n, worksheetFilled: !!(r.quarter.worksheet && r.quarter.worksheet.filled), sraDone: !!(r.quarter.sra && r.quarter.sra.done) } : null
    } : null
  };
}

module.exports = { reportInfo, saveReportInfo, markGenerated, gather, summary, monthLabel, quarterStart };
